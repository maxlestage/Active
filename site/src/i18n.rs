//! Interface texts in English, French and Spanish.

use crate::routes::Lang;

pub struct Dict {
    pub lang_name: &'static str,
    pub locale: &'static str,
    pub skip: &'static str,
    pub nav: Nav,
    pub home: Home,
    pub docs: Docs,
    pub not_found: NotFound,
    /// The page shown offline (title, text, link to the home page).
    pub offline: NotFound,
    pub footer: Footer,
}

pub struct Nav {
    pub docs: &'static str,
    pub features: &'static str,
    pub playground: &'static str,
    pub benchmarks: &'static str,
    pub start: &'static str,
    pub menu: &'static str,
}

pub struct Item {
    pub title: &'static str,
    pub text: &'static str,
}

pub struct Stat {
    pub value: f64,
    pub decimals: usize,
    pub prefix: &'static str,
    pub suffix: &'static str,
    pub label: &'static str,
}

pub struct Play {
    pub title: &'static str,
    pub description: &'static str,
    pub path: &'static str,
    pub title_value: &'static str,
    pub description_value: &'static str,
    pub path_value: &'static str,
    pub output: &'static str,
    pub google: &'static str,
    pub social: &'static str,
    pub server: &'static str,
    pub browser: &'static str,
}

pub struct Home {
    pub title: &'static str,
    pub description: &'static str,
    pub eyebrow: &'static str,
    pub hero: [&'static str; 3],
    pub lead: &'static str,
    pub cta: &'static str,
    pub dust: &'static str,
    pub particles: &'static str,
    pub scroll: &'static str,
    pub marquee: [&'static str; 10],
    pub manifesto: &'static str,
    pub features_title: &'static str,
    pub features: [Item; 4],
    pub stats: [Stat; 4],
    pub code_title: &'static str,
    pub code_text: &'static str,
    pub tabs: [&'static str; 4],
    pub play_title: &'static str,
    pub play_text: &'static str,
    pub play: Play,
    pub bench_title: &'static str,
    pub bench_text: &'static str,
    pub bench_size: &'static str,
    pub bench_ssr: &'static str,
    pub bench_link: &'static str,
    pub steps_title: &'static str,
    pub steps: [Item; 3],
    pub cta_title: &'static str,
    pub cta_text: &'static str,
    pub cta_docs: &'static str,
}

pub struct Docs {
    pub title: &'static str,
    pub description: &'static str,
    pub intro: &'static str,
    pub search: &'static str,
    pub search_hint: &'static str,
    pub no_results: &'static str,
    pub on_this_page: &'static str,
    pub prev: &'static str,
    pub next: &'static str,
    pub categories: [Item; 7],
}

pub struct NotFound {
    pub title: &'static str,
    pub text: &'static str,
    pub back: &'static str,
}

pub struct Footer {
    pub tagline: &'static str,
    /// The call to action, followed by the project name: "Start building with *Active*".
    pub start: &'static str,
    /// Accessible name of the install command chip.
    pub install: &'static str,
    pub rust_only: &'static str,
    pub product: &'static str,
    pub learn: &'static str,
    pub project: &'static str,
    pub language: &'static str,
    pub quick_start: &'static str,
    pub api: &'static str,
    pub benchmarks: &'static str,
    pub components: &'static str,
    pub seo: &'static str,
    pub islands: &'static str,
    pub faq: &'static str,
    pub deploy: &'static str,
    pub license: &'static str,
    /// The sister projects: title, one-line introduction, the "you are here" mark and one
    /// line per project, in the order of [`crate::server::pages::ECOSYSTEM`].
    pub ecosystem: &'static str,
    pub ecosystem_text: &'static str,
    pub here: &'static str,
    pub projects: [&'static str; 5],
    /// The signature: "Designed and built by", the name, then where it was made.
    pub by: &'static str,
    pub crafted: &'static str,
    pub rights: &'static str,
    pub proprietary: &'static str,
    pub built: &'static str,
    pub top: &'static str,
}

pub fn t(lang: Lang) -> &'static Dict {
    match lang {
        Lang::En => &EN,
        Lang::Fr => &FR,
        Lang::Es => &ES,
    }
}

