//! The counter app: a button that increments a number shown next to it, starting at
//! [`COUNTER_START`]. Every framework renders the same markup:
//!
//! ```html
//! <button id="inc">+1</button><span id="count">3</span>
//! ```
//!
//! Its page loads the browser bundle exactly like `active`'s `Document::client` does
//! (preloads in `<head>`, then the one-line module script that starts a wasm-bindgen
//! bundle), so the browser benchmark compares the frameworks, not their loaders.

/// Initial value of the counter.
pub const COUNTER_START: i32 = 3;

/// URL of the JavaScript glue generated by `wasm-bindgen --target web` for library `lib`.
pub fn bundle_js(lib: &str) -> String {
    format!("/pkg/{lib}.js")
}

/// URL of the WebAssembly binary generated by `wasm-bindgen --target web` for library `lib`.
pub fn bundle_wasm(lib: &str) -> String {
    format!("/pkg/{lib}_bg.wasm")
}

/// A complete counter page whose `<body>` is `body` (already rendered by the framework)
/// and which starts the browser bundle of library `lib`.
pub fn counter_page(lib: &str, body: &str) -> String {
    let (js, wasm) = (bundle_js(lib), bundle_wasm(lib));
    format!(
        concat!(
            r#"<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"/>"#,
            r#"<meta name="viewport" content="width=device-width, initial-scale=1"/><title>Counter</title>"#,
            r#"<link rel="modulepreload" href="{js}"/>"#,
            r#"<link rel="preload" href="{wasm}" as="fetch" type="application/wasm" crossorigin=""/>"#,
            r#"<script type="module">import init from "{js}";init({{module_or_path:"{wasm}"}});</script>"#,
            r#"</head><body>{body}</body></html>"#,
        ),
        js = js,
        wasm = wasm,
        body = body
    )
}

/// Records `performance.now()` (milliseconds since the navigation started) in the `<body>`
/// attribute `attribute`, where the benchmark reads it through the DevTools protocol.
///
/// Every counter calls `mark("data-start")` first thing in its `#[wasm_bindgen(start)]`
/// function and `mark("data-ready")` as soon as the button is interactive. Does nothing on
/// the server, so components can call it unconditionally.
pub fn mark(attribute: &str) {
    #[cfg(target_arch = "wasm32")]
    {
        let Some(window) = web_sys::window() else {
            return;
        };
        let now = window.performance().map_or(-1.0, |p| p.now());
        if let Some(body) = window.document().and_then(|d| d.body()) {
            let _ = body.set_attribute(attribute, &now.to_string());
        }
    }
    #[cfg(not(target_arch = "wasm32"))]
    let _ = attribute;
}
