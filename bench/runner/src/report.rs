//! Writes `RESULTS.md` from `results/*.json`.

use std::fmt::Write;

use crate::browser::BrowserReport;
use crate::environment::Environment;
use crate::frameworks::{BASELINE, COUNTERS, SSR};
use crate::ssr::SsrReport;
use crate::wasm::WasmReport;
use crate::{Context, Result};

pub fn write(ctx: &Context) -> Result<()> {
    let env: Option<Environment> = ctx.load("environment")?;
    let ssr: Option<SsrReport> = ctx.load("ssr")?;
    let wasm: Option<WasmReport> = ctx.load("wasm")?;
    let browser: Option<BrowserReport> = ctx.load("browser")?;

    let mut md = String::new();
    md += "# Benchmark results\n\n";
    md += "Generated by `cargo run --release -p runner` (method, caveats and how to run it: [README.md](README.md); raw data: [`results/`](results/)). ";
    md += "The numbers come from one machine: compare the frameworks with each other, not with other machines.\n\n";
    let quick = env.as_ref().is_some_and(|e| e.quick)
        || ssr.as_ref().is_some_and(|r| r.quick)
        || browser.as_ref().is_some_and(|r| r.quick);
    if quick {
        md += "> **Quick run** (`--quick`): shortened measurements, only meant to check the setup.\n\n";
    }
    summary(&mut md, ssr.as_ref(), wasm.as_ref(), browser.as_ref());
    if let Some(env) = &env {
        environment(&mut md, env, wasm.as_ref());
    }
    if let Some(ssr) = &ssr {
        server_rendering(&mut md, ssr);
    }
    if let Some(wasm) = &wasm {
        bundle_size(&mut md, wasm);
    }
    if let Some(browser) = &browser {
        time_to_interactive(&mut md, browser);
    }

    let path = ctx.bench.join("RESULTS.md");
    std::fs::write(&path, md)?;
    eprintln!("wrote {}", path.display());
    Ok(())
}

/// Where `active` stands, computed from the results (rank 1 is the best).
fn summary(
    md: &mut String,
    ssr: Option<&SsrReport>,
    wasm: Option<&WasmReport>,
    browser: Option<&BrowserReport>,
) {
    let mut lines = Vec::new();
    if let Some(ssr) = ssr {
        let times: Vec<(&str, f64)> = ssr
            .results
            .iter()
            .filter_map(|r| Some((r.id.as_str(), r.us_per_page?)))
            .collect();
        let baseline = times
            .iter()
            .find(|(id, _)| *id == BASELINE)
            .map(|(_, us)| *us);
        if let (Some(&(_, us)), Some(baseline)) =
            (times.iter().find(|(id, _)| *id == "active"), baseline)
        {
            let rank = 1 + times.iter().filter(|(_, other)| *other < us).count();
            lines.push(format!(
                "**Server rendering**: {us:.2} µs per page, ×{:.2} the hand-written baseline (rank {rank} of {}).",
                us / baseline,
                times.len()
            ));
        }
    }
    if let Some(r) = wasm.and_then(|w| w.results.iter().find(|r| r.id == "active")) {
        let all = &wasm.expect("found in it").results;
        let rank = 1 + all.iter().filter(|o| o.total_gzip < r.total_gzip).count();
        lines.push(format!(
            "**Bundle**: {} gzip in total for the counter (rank {rank} of {}).",
            kb(r.total_gzip),
            all.len()
        ));
    }
    if let Some(r) = browser.and_then(|b| b.results.iter().find(|r| r.id == "active")) {
        let all = &browser.expect("found in it").results;
        let ranks: Vec<String> = r
            .profiles
            .iter()
            .enumerate()
            .map(|(i, p)| {
                let rank = 1 + all
                    .iter()
                    .filter(|o| o.profiles[i].median_ready_ms < p.median_ready_ms)
                    .count();
                let (min, max) = range(&p.ready_ms);
                format!(
                    "{:.1} ms ({}; rank {rank} of {}; loads from {min:.0} to {max:.0} ms)",
                    p.median_ready_ms,
                    p.profile,
                    all.len()
                )
            })
            .collect();
        lines.push(format!(
            "**Browser**: interactive after {}.",
            ranks.join(" and ")
        ));
    }
    if !lines.is_empty() {
        md.push_str("## Summary for `active`\n\n");
        for line in lines {
            let _ = writeln!(md, "- {line}");
        }
        md.push('\n');
    }
}

fn environment(md: &mut String, env: &Environment, wasm: Option<&WasmReport>) {
    md.push_str("## Environment\n\n| | |\n| --- | --- |\n");
    let memory = env
        .memory_gib
        .map_or_else(String::new, |gib| format!(", {gib} GiB of memory"));
    let rows = [
        ("Date", env.date.clone()),
        ("CPU", format!("{} ({} logical cores{memory})", env.cpu, env.logical_cores)),
        ("OS", env.os.clone()),
        ("Rust", format!("`{}`", env.rustc)),
        ("wasm-bindgen", format!("`{}`", wasm.map_or(env.wasm_bindgen.as_str(), |w| w.wasm_bindgen.as_str()))),
        ("Chromium", env.chromium.clone().unwrap_or_else(|| "not run".into())),
        (
            "Cargo profiles",
            "servers: `release` (`opt-level = 3`, `lto = true`, `codegen-units = 1`, `strip = true`); browser bundles: \
             `wasm-release` (the same with `opt-level = \"s\"` and `panic = \"abort\"`), no `wasm-opt`"
                .into(),
        ),
    ];
    for (key, value) in rows {
        let _ = writeln!(md, "| {key} | {value} |");
    }
    md.push('\n');
}

fn server_rendering(md: &mut String, report: &SsrReport) {
    let _ = write!(
        md,
        "## 1. Server-side rendering\n\n\
         Every implementation renders the same complete document for product page `i` (`i` changes on every \
         iteration): `<html lang=\"en\">`, a `<head>` with the 11 SEO tags (`<title>` with the template \
         `Produit {{i}} · Acme`, description, canonical, `og:title`, `og:description`, `og:type`, `og:url`, \
         `og:image`, `og:site_name`, `twitter:card`, `twitter:site`) and one JSON-LD script, and a `<body>` with \
         an `<h1>` and a `<ul>` of 30 `<li>Option {{k}} — {{i·k}} €</li>`.\n\n\
         Each implementation runs in its own process. Before timing, its output is checked tag by tag (each SEO tag \
         exactly once, in `<head>`, with the expected value; the JSON-LD; the `<h1>`; the 30 items). Then it renders \
         for {warmup:.1} s to warm up and for {measure:.1} s in batches of about 10 ms; a run's result is its median \
         batch (µs per page). The table shows the median of {runs} run(s), started in turn so that a noisy moment \
         does not hit a single implementation. p10–p90 is the spread of the batches in the median run.\n\n",
        warmup = report.warmup_ms as f64 / 1000.0,
        measure = report.measure_ms as f64 / 1000.0,
        runs = report.runs,
    );
    md.push_str("| Implementation | Versions | µs / page | pages / s | vs hand-written | p10–p90 (µs) | Page bytes |\n");
    md.push_str("| --- | --- | ---: | ---: | ---: | ---: | ---: |\n");
    let baseline = report
        .results
        .iter()
        .find(|r| r.id == BASELINE)
        .and_then(|r| r.us_per_page);
    let mut rows: Vec<_> = report.results.iter().collect();
    rows.sort_by(|a, b| {
        a.us_per_page
            .unwrap_or(f64::MAX)
            .total_cmp(&b.us_per_page.unwrap_or(f64::MAX))
    });
    for r in rows {
        let name = if r.id == "active" {
            format!("**{}**", r.name)
        } else {
            r.name.clone()
        };
        let versions = if r.versions.is_empty() {
            "—".to_string()
        } else {
            r.versions.clone()
        };
        match (r.us_per_page, &r.error) {
            (Some(us), None) => {
                let ratio = baseline.map_or_else(|| "—".into(), |b| format!("×{:.2}", us / b));
                let spread = r
                    .runs
                    .iter()
                    .min_by(|a, b| {
                        (a.us_per_page - us)
                            .abs()
                            .total_cmp(&(b.us_per_page - us).abs())
                    })
                    .map_or_else(String::new, |run| format!("{:.2}–{:.2}", run.p10, run.p90));
                let bytes = r.bytes.map_or_else(String::new, |b| group(b as u64));
                let _ = writeln!(
                    md,
                    "| {name} | {versions} | {us:.2} | {} | {ratio} | {spread} | {bytes} |",
                    group((1e6 / us).round() as u64)
                );
            }
            (_, error) => {
                let _ = writeln!(
                    md,
                    "| {name} | {versions} | failed: {} | | | | |",
                    error.as_deref().unwrap_or("no result")
                );
            }
        }
    }
    md.push_str("\nHow each page is produced:\n\n");
    for bench in SSR {
        let _ = writeln!(md, "- **{}**: {}.", bench.name, bench.how);
    }
    md.push_str(
        "\nPage bytes differ slightly: void elements written `<meta>` or `<meta/>`, hydration markers (Leptos `<!>`, \
         Yew `<!--<[]>-->`, Sycamore `data-hk` attributes and `<!--/-->`), leptos_meta's `<!--HEAD-->` and `active`'s \
         `<style>active-island{display:contents}</style>`.\n\n",
    );
}

fn bundle_size(md: &mut String, report: &WasmReport) {
    md.push_str(
        "## 2. WebAssembly bundle size\n\n\
         The same counter in every framework: a button that increments the number next to it, starting at 3, \
         server-rendered and taken over by the browser bundle. Built for `wasm32-unknown-unknown` with the \
         `wasm-release` profile, then `wasm-bindgen --target web`; no `wasm-opt`. \"JS glue\" is every JavaScript \
         file wasm-bindgen generated (the module and its snippets), each compressed on its own. gzip is level 9. \
         kB = 1000 bytes.\n\n",
    );
    md.push_str("| Framework | Versions | Browser mode | .wasm | .wasm gzip | JS glue gzip | Total gzip |\n");
    md.push_str("| --- | --- | --- | ---: | ---: | ---: | ---: |\n");
    let mut rows: Vec<_> = report.results.iter().collect();
    rows.sort_by_key(|r| r.total_gzip);
    for r in rows {
        let name = if r.id == "active" {
            format!("**{}**", r.name)
        } else {
            r.name.clone()
        };
        let files = if r.js_files > 1 {
            format!(" ({} files)", r.js_files)
        } else {
            String::new()
        };
        let _ = writeln!(
            md,
            "| {name} | {} | {} | {} | {} | {}{files} | **{}** |",
            r.versions,
            r.mode,
            kb(r.wasm_bytes),
            kb(r.wasm_gzip),
            kb(r.js_gzip),
            kb(r.total_gzip)
        );
    }
    md.push('\n');
}

fn time_to_interactive(md: &mut String, report: &BrowserReport) {
    let _ = write!(
        md,
        "## 3. Browser: time to interactive\n\n\
         Headless {chromium}, driven from Rust with chromiumoxide (no JavaScript evaluated). Each counter page \
         (server HTML + bundle, served by a small Rust server on 127.0.0.1) is loaded {loads} times per network \
         profile after one warm-up round, in turn with the other apps (one load of each, then again), with the \
         HTTP cache disabled; the table shows medians. The app writes \
         `performance.now()` (milliseconds since navigation start) into `<body data-start>` when its wasm starts \
         and `<body data-ready>` when the button is interactive; the runner reads them with DOM queries. \
         \"100 ms RTT\" adds 100 ms of latency to every request (`Network.emulateNetworkConditions`, bandwidth not \
         limited). Every page then gets one real click: the number must go from 3 to 4.\n\n",
        chromium = report.chromium,
        loads = report.loads,
    );
    let profiles: Vec<&str> = report.results.first().map_or_else(Vec::new, |r| {
        r.profiles.iter().map(|p| p.profile.as_str()).collect()
    });
    md.push_str("| Framework | Browser mode |");
    for profile in &profiles {
        let _ = write!(md, " Interactive, {profile}: median (min–max) |");
    }
    md.push_str(" wasm starts | wasm start → interactive | Click 3 → 4 |\n| --- | --- |");
    md.push_str(&" ---: |".repeat(profiles.len() + 2));
    md.push_str(" :---: |\n");
    let mut rows: Vec<_> = report.results.iter().collect();
    rows.sort_by(|a, b| {
        a.profiles[0]
            .median_ready_ms
            .total_cmp(&b.profiles[0].median_ready_ms)
    });
    for r in rows {
        let name = if r.id == "active" {
            format!("**{}**", r.name)
        } else {
            r.name.clone()
        };
        let _ = write!(md, "| {name} | {} |", r.mode);
        for p in &r.profiles {
            let (min, max) = range(&p.ready_ms);
            let _ = write!(md, " {:.1} ms ({min:.0}–{max:.0}) |", p.median_ready_ms);
        }
        let (start, own) = r.profiles.first().map_or((f64::NAN, f64::NAN), |p| {
            (p.median_start_ms, p.median_start_to_ready_ms)
        });
        let click = if r.click.ok {
            "✅".to_string()
        } else {
            format!("❌ ({} → {})", r.click.before, r.click.after)
        };
        let _ = writeln!(md, " {start:.1} ms | {own:.2} ms | {click} |");
    }
    md.push_str("\n\"wasm starts\" (when the module's start function runs: HTML, JavaScript and WebAssembly fetched and \
                 compiled) and \"wasm start → interactive\" (the framework's own work: hydration, or the first render \
                 for client-side rendering) are measured on localhost. `performance.now()` has a 0.1 ms \
                 resolution in Chromium (pages are not cross-origin isolated). When `data-ready` is recorded:\n\n");
    for app in COUNTERS {
        let _ = writeln!(md, "- **{}**: {}.", app.name, app.ready);
    }
    md.push('\n');
}

/// Smallest and largest value.
fn range(values: &[f64]) -> (f64, f64) {
    let min = values.iter().copied().fold(f64::INFINITY, f64::min);
    let max = values.iter().copied().fold(f64::NEG_INFINITY, f64::max);
    (min, max)
}

/// `12345` → `12 345`.
fn group(n: u64) -> String {
    let digits = n.to_string();
    let mut out = String::new();
    for (i, c) in digits.chars().enumerate() {
        if i > 0 && (digits.len() - i).is_multiple_of(3) {
            out.push('\u{202f}');
        }
        out.push(c);
    }
    out
}

/// Bytes in kB with one decimal.
fn kb(bytes: u64) -> String {
    format!("{:.1} kB", bytes as f64 / 1000.0)
}
