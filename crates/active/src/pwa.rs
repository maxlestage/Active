//! Progressive Web App: a web app manifest and a service worker, so that a site can be
//! installed on a phone's home screen, opens full screen like an app, and keeps working
//! offline.
//!
//! ```
//! use active::pwa::{Manifest, ServiceWorker};
//! use active::{Document, html::h1};
//!
//! let manifest = Manifest::new("Acme")
//!     .short_name("Acme")
//!     .description("The Acme app.")
//!     .theme_color("#6d4aff")
//!     .background_color("#0b0b10")
//!     .icon("/icon-192.png", "192x192", "image/png")
//!     .icon("/icon-512.png", "512x512", "image/png")
//!     .maskable_icon("/icon-maskable.png", "512x512", "image/png");
//! // Serve it at /manifest.webmanifest (Content-Type: application/manifest+json).
//! let json = manifest.to_json();
//! assert!(json.starts_with(r#"{"name":"Acme","short_name":"Acme""#));
//!
//! // Serve it at /sw.js (Content-Type: text/javascript, Cache-Control: no-cache).
//! let worker = ServiceWorker::new("acme", "v1")
//!     .precache(["/", "/app.css", "/icon-192.png"])
//!     .offline_page("/")
//!     .network_only("/api/")
//!     .to_js();
//! assert!(worker.contains(r#"const PRECACHE = ["/","/app.css","/icon-192.png"];"#));
//!
//! let html = Document::new(h1().text("Hello"))
//!     .manifest("/manifest.webmanifest", &manifest)
//!     .service_worker("/sw.js")
//!     .render();
//! assert!(html.contains(r#"<link rel="manifest" href="/manifest.webmanifest"/>"#));
//! assert!(html.contains(r##"<meta name="theme-color" content="#6d4aff"/>"##));
//! assert!(html.contains(r#"navigator.serviceWorker.register("/sw.js")"#));
//! ```
//!
//! The service worker is a small script generated by [`ServiceWorker::to_js`]: browsers
//! only run service workers as scripts. Its strategy:
//!
//! - **pages** (navigations): the network first, so visitors always get the latest
//!   version; the cached copy when offline, else the offline page;
//! - **other files** of the site (styles, the WebAssembly bundle, images, fonts): the
//!   cached copy at once, refreshed in the background;
//! - **`network_only` prefixes** (an API…) and other sites: never cached;
//! - a new version (another `version` string) replaces the old caches when it activates.

use crate::escape::escape_into;

/// An icon of the [`Manifest`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Icon {
    /// URL of the image.
    pub src: String,
    /// `"192x192"`, `"512x512"`, or `"any"` for SVG.
    pub sizes: String,
    /// `"image/png"`, `"image/svg+xml"`…
    pub mime: String,
    /// `"any"`, `"maskable"` (safe zone for round or squircle icons) or `"monochrome"`.
    pub purpose: String,
}

/// The web app manifest (`manifest.webmanifest`): the name, icons and colors the phone
/// uses when the site is installed.
#[derive(Clone, Debug, PartialEq, Eq)]
#[must_use]
pub struct Manifest {
    name: String,
    short_name: Option<String>,
    description: Option<String>,
    id: Option<String>,
    start_url: String,
    scope: Option<String>,
    display: String,
    orientation: Option<String>,
    theme_color: String,
    background_color: String,
    lang: Option<String>,
    categories: Vec<String>,
    icons: Vec<Icon>,
}

impl Manifest {
    /// A manifest named `name`, opening at `./` in `standalone` mode (full screen, no
    /// browser bar).
    pub fn new(name: impl Into<String>) -> Self {
        Manifest {
            name: name.into(),
            short_name: None,
            description: None,
            id: None,
            start_url: "./".into(),
            scope: None,
            display: "standalone".into(),
            orientation: None,
            theme_color: "#000000".into(),
            background_color: "#ffffff".into(),
            lang: None,
            categories: Vec::new(),
            icons: Vec::new(),
        }
    }

    /// The name under the icon (12 characters at most look good).
    pub fn short_name(mut self, name: impl Into<String>) -> Self {
        self.short_name = Some(name.into());
        self
    }

    /// What the app does.
    pub fn description(mut self, description: impl Into<String>) -> Self {
        self.description = Some(description.into());
        self
    }

    /// The identity of the app (defaults to `start_url`).
    pub fn id(mut self, id: impl Into<String>) -> Self {
        self.id = Some(id.into());
        self
    }

    /// The page opened by the icon (`./` by default: relative to the manifest).
    pub fn start_url(mut self, url: impl Into<String>) -> Self {
        self.start_url = url.into();
        self
    }

    /// The URLs that belong to the app (defaults to the manifest's folder).
    pub fn scope(mut self, scope: impl Into<String>) -> Self {
        self.scope = Some(scope.into());
        self
    }

    /// `standalone` (default), `fullscreen`, `minimal-ui` or `browser`.
    pub fn display(mut self, display: impl Into<String>) -> Self {
        self.display = display.into();
        self
    }

    /// `portrait`, `landscape`, `any`…
    pub fn orientation(mut self, orientation: impl Into<String>) -> Self {
        self.orientation = Some(orientation.into());
        self
    }

    /// The color of the status bar and of the window title.
    pub fn theme_color(mut self, color: impl Into<String>) -> Self {
        self.theme_color = color.into();
        self
    }

    /// The color of the splash screen while the app starts.
    pub fn background_color(mut self, color: impl Into<String>) -> Self {
        self.background_color = color.into();
        self
    }

    /// The language of the texts (`fr`, `en-US`…).
    pub fn lang(mut self, lang: impl Into<String>) -> Self {
        self.lang = Some(lang.into());
        self
    }

    /// Store categories (`productivity`, `developer`…).
    pub fn categories<I, S>(mut self, categories: I) -> Self
    where
        I: IntoIterator<Item = S>,
        S: Into<String>,
    {
        self.categories = categories.into_iter().map(Into::into).collect();
        self
    }

    /// An icon. Phones want at least a 192×192 and a 512×512 PNG.
    pub fn icon(
        mut self,
        src: impl Into<String>,
        sizes: impl Into<String>,
        mime: impl Into<String>,
    ) -> Self {
        self.icons.push(Icon {
            src: src.into(),
            sizes: sizes.into(),
            mime: mime.into(),
            purpose: "any".into(),
        });
        self
    }

    /// An icon drawn for round and squircle masks: its content stays in the central
    /// circle (80% of the size).
    pub fn maskable_icon(
        mut self,
        src: impl Into<String>,
        sizes: impl Into<String>,
        mime: impl Into<String>,
    ) -> Self {
        self.icons.push(Icon {
            src: src.into(),
            sizes: sizes.into(),
            mime: mime.into(),
            purpose: "maskable".into(),
        });
        self
    }

    /// The name.
    pub fn name(&self) -> &str {
        &self.name
    }

    /// The theme color (also written as `<meta name="theme-color">` by
    /// [`Document::manifest`](crate::Document::manifest)).
    pub fn theme(&self) -> &str {
        &self.theme_color
    }

    /// The icons.
    pub fn icons(&self) -> &[Icon] {
        &self.icons
    }

    /// The manifest as JSON.
    pub fn to_json(&self) -> String {
        let mut out = String::with_capacity(512);
        out.push('{');
        field(&mut out, "name", &self.name, true);
        if let Some(v) = &self.short_name {
            field(&mut out, "short_name", v, false);
        }
        if let Some(v) = &self.description {
            field(&mut out, "description", v, false);
        }
        if let Some(v) = &self.id {
            field(&mut out, "id", v, false);
        }
        field(&mut out, "start_url", &self.start_url, false);
        if let Some(v) = &self.scope {
            field(&mut out, "scope", v, false);
        }
        field(&mut out, "display", &self.display, false);
        if let Some(v) = &self.orientation {
            field(&mut out, "orientation", v, false);
        }
        field(&mut out, "theme_color", &self.theme_color, false);
        field(&mut out, "background_color", &self.background_color, false);
        if let Some(v) = &self.lang {
            field(&mut out, "lang", v, false);
        }
        if !self.categories.is_empty() {
            out.push_str(",\"categories\":");
            string_array(&mut out, &self.categories);
        }
        out.push_str(",\"icons\":[");
        for (i, icon) in self.icons.iter().enumerate() {
            if i > 0 {
                out.push(',');
            }
            out.push('{');
            field(&mut out, "src", &icon.src, true);
            field(&mut out, "sizes", &icon.sizes, false);
            field(&mut out, "type", &icon.mime, false);
            field(&mut out, "purpose", &icon.purpose, false);
            out.push('}');
        }
        out.push_str("]}");
        out
    }
}

/// The offline service worker of a site (see the [module](self) documentation for its
/// strategy).
#[derive(Clone, Debug, PartialEq, Eq)]
#[must_use]
pub struct ServiceWorker {
    name: String,
    version: String,
    precache: Vec<String>,
    offline: Option<String>,
    network_only: Vec<String>,
}

impl ServiceWorker {
    /// A service worker whose cache is named `{name}-{version}`. Change `version` with
    /// every deployment (a hash of the files, the crate version…): the new worker then
    /// replaces the old caches.
    pub fn new(name: impl Into<String>, version: impl Into<String>) -> Self {
        ServiceWorker {
            name: name.into(),
            version: version.into(),
            precache: Vec::new(),
            offline: None,
            network_only: Vec::new(),
        }
    }

    /// URLs downloaded when the app is installed, available offline from the first
    /// visit: the start page, the stylesheet, the WebAssembly bundle, the icons…
    pub fn precache<I, S>(mut self, urls: I) -> Self
    where
        I: IntoIterator<Item = S>,
        S: Into<String>,
    {
        self.precache.extend(urls.into_iter().map(Into::into));
        self
    }

    /// The page shown when a page was never visited and the network is down (it is
    /// precached).
    pub fn offline_page(mut self, url: impl Into<String>) -> Self {
        let url = url.into();
        if !self.precache.contains(&url) {
            self.precache.push(url.clone());
        }
        self.offline = Some(url);
        self
    }

    /// URLs starting with `prefix` (an API: `/api/`) always go to the network.
    pub fn network_only(mut self, prefix: impl Into<String>) -> Self {
        self.network_only.push(prefix.into());
        self
    }

    /// The name of the cache.
    pub fn cache_name(&self) -> String {
        format!("{}-{}", self.name, self.version)
    }

    /// The script, to serve at the root of the site (its folder is its scope).
    pub fn to_js(&self) -> String {
        let mut precache = String::new();
        string_array(&mut precache, &self.precache);
        let mut network_only = String::new();
        string_array(&mut network_only, &self.network_only);
        let mut cache = String::new();
        json_string(&mut cache, &self.cache_name());
        let mut prefix = String::new();
        json_string(&mut prefix, &format!("{}-", self.name));
        let mut offline = String::new();
        match &self.offline {
            Some(url) => json_string(&mut offline, url),
            None => offline.push_str("null"),
        }
        SCRIPT
            .replace("__CACHE__", &cache)
            .replace("__PREFIX__", &prefix)
            .replace("__PRECACHE__", &precache)
            .replace("__NETWORK_ONLY__", &network_only)
            .replace("__OFFLINE__", &offline)
    }
}

const SCRIPT: &str = r#"// Service worker generated by active (https://github.com/maxlestage/Active).
const CACHE = __CACHE__;
const PREFIX = __PREFIX__;
const PRECACHE = __PRECACHE__;
const NETWORK_ONLY = __NETWORK_ONLY__;
const OFFLINE = __OFFLINE__;

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(
        keys.filter((key) => key.startsWith(PREFIX) && key !== CACHE).map((key) => caches.delete(key)),
      ))
      .then(() => self.clients.claim()),
  );
});

function keep(request, response) {
  if (response.ok && response.type === "basic") {
    const copy = response.clone();
    caches.open(CACHE).then((cache) => cache.put(request, copy));
  }
  return response;
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (NETWORK_ONLY.some((prefix) => url.pathname.startsWith(prefix))) return;

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((response) => keep(request, response))
        .catch(() => caches.match(request)
          .then((cached) => cached || (OFFLINE ? caches.match(OFFLINE) : undefined))
          .then((response) => response || Response.error())),
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      const network = fetch(request).then((response) => keep(request, response));
      if (cached) {
        event.waitUntil(network.catch(() => {}));
        return cached;
      }
      return network;
    }),
  );
});
"#;

/// The inline script that registers the service worker at `url`, once the page has
/// loaded (written by [`Document::service_worker`](crate::Document::service_worker); with
/// a strict Content-Security-Policy, allow its hash).
pub fn register_script(url: &str) -> String {
    let mut quoted = String::new();
    json_string(&mut quoted, url);
    // `<` is escaped by json_string: the script cannot close its element.
    format!(
        "if(\"serviceWorker\"in navigator)addEventListener(\"load\",()=>navigator.serviceWorker.register({quoted}))"
    )
}

/// The `<head>` tags of an installable page.
pub(crate) fn head_tags(href: &str, manifest: &Manifest) -> String {
    let mut out = String::with_capacity(256);
    out.push_str(r#"<link rel="manifest" href=""#);
    escape_into(&mut out, href);
    out.push_str(r#""/><meta name="theme-color" content=""#);
    escape_into(&mut out, &manifest.theme_color);
    out.push_str(r#""/><meta name="mobile-web-app-capable" content="yes"/><meta name="apple-mobile-web-app-capable" content="yes"/><meta name="apple-mobile-web-app-title" content=""#);
    escape_into(
        &mut out,
        manifest.short_name.as_deref().unwrap_or(&manifest.name),
    );
    out.push_str(r#""/>"#);
    if let Some(icon) = manifest
        .icons
        .iter()
        .filter(|i| i.purpose == "any" && i.mime == "image/png")
        .max_by_key(|i| {
            i.sizes
                .split('x')
                .next()
                .and_then(|w| w.parse::<u32>().ok())
        })
    {
        out.push_str(r#"<link rel="apple-touch-icon" href=""#);
        escape_into(&mut out, &icon.src);
        out.push_str(r#""/>"#);
    }
    out
}

fn field(out: &mut String, name: &str, value: &str, first: bool) {
    if !first {
        out.push(',');
    }
    out.push('"');
    out.push_str(name);
    out.push_str("\":");
    json_string(out, value);
}

fn string_array(out: &mut String, values: &[String]) {
    out.push('[');
    for (i, value) in values.iter().enumerate() {
        if i > 0 {
            out.push(',');
        }
        json_string(out, value);
    }
    out.push(']');
}

/// A JSON (and JavaScript) string literal that cannot close a `<script>` element.
fn json_string(out: &mut String, s: &str) {
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '<' => out.push_str("\\u003c"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\u{2028}' => out.push_str("\\u2028"),
            '\u{2029}' => out.push_str("\\u2029"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn manifest_json_escapes_and_lists_icons() {
        let json = Manifest::new("A \"quoted\" </script> name")
            .lang("fr")
            .categories(["developer"])
            .icon("/i.png", "192x192", "image/png")
            .maskable_icon("/m.png", "512x512", "image/png")
            .to_json();
        assert_eq!(
            json,
            concat!(
                r#"{"name":"A \"quoted\" \u003c/script> name","start_url":"./","display":"standalone","#,
                r##""theme_color":"#000000","background_color":"#ffffff","lang":"fr","categories":["developer"],"##,
                r#""icons":[{"src":"/i.png","sizes":"192x192","type":"image/png","purpose":"any"},"#,
                r#"{"src":"/m.png","sizes":"512x512","type":"image/png","purpose":"maskable"}]}"#
            )
        );
    }

    #[test]
    fn the_worker_has_its_cache_lists_and_offline_page() {
        let js = ServiceWorker::new("site", "abc")
            .precache(["/", "/app.css"])
            .offline_page("/offline/")
            .network_only("/api/")
            .to_js();
        assert!(js.contains(r#"const CACHE = "site-abc";"#));
        assert!(js.contains(r#"const PREFIX = "site-";"#));
        assert!(js.contains(r#"const PRECACHE = ["/","/app.css","/offline/"];"#));
        assert!(js.contains(r#"const NETWORK_ONLY = ["/api/"];"#));
        assert!(js.contains(r#"const OFFLINE = "/offline/";"#));
        assert!(!js.contains("__"), "every placeholder is replaced");
        let bare = ServiceWorker::new("site", "1").to_js();
        assert!(bare.contains("const OFFLINE = null;"));
        assert!(bare.contains("const PRECACHE = [];"));
    }

    #[test]
    fn head_tags_and_registration() {
        let manifest = Manifest::new("Acme")
            .short_name("Ac")
            .theme_color("#123456")
            .icon("/s.png", "192x192", "image/png")
            .icon("/l.png", "512x512", "image/png")
            .icon("/v.svg", "any", "image/svg+xml");
        let tags = head_tags("/manifest.webmanifest", &manifest);
        assert!(tags.starts_with(r#"<link rel="manifest" href="/manifest.webmanifest"/>"#));
        assert!(tags.contains(r##"<meta name="theme-color" content="#123456"/>"##));
        assert!(tags.contains(r#"<meta name="apple-mobile-web-app-title" content="Ac"/>"#));
        assert!(tags.ends_with(r#"<link rel="apple-touch-icon" href="/l.png"/>"#));
        assert_eq!(
            register_script("/x</script>.js"),
            r#"if("serviceWorker"in navigator)addEventListener("load",()=>navigator.serviceWorker.register("/x\u003c/script>.js"))"#
        );
    }
}
